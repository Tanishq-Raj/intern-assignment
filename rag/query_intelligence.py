@dataclass
class SearchPlan:
    """Direct search plan generated by the LLM query intelligence layer."""

    semantic_query: str
    where: dict[str, Any] | None = None


ALLOWED_FIELDS = {"countries", "genres", "type", "rating", "release_year"}
ALLOWED_LOGICAL_OPERATORS = {"$and", "$or"}
ALLOWED_YEAR_OPERATORS = {"$eq", "$gte", "$lte", "$gt", "$lt"}


def _fallback_search_plan(question: str) -> SearchPlan:
    """Return fallback semantic-only search plan if LLM planning fails."""
    return SearchPlan(semantic_query=question, where=None)


def _strip_markdown_fences(content: str) -> str:
    """Remove markdown JSON fences if the LLM wraps response in them."""
    content = content.strip()
    if content.startswith("```json"):
        content = content.removeprefix("```json").strip()
    if content.startswith("```"):
        content = content.removeprefix("```").strip()
    if content.endswith("```"):
        content = content.removesuffix("```").strip()
    return content


def _load_json_object(content: str) -> dict[str, Any]:
    """Load a JSON object from LLM response text."""
    content = _strip_markdown_fences(content)
    try:
        payload = json.loads(content)
    except json.JSONDecodeError as error:
        raise RuntimeError(f"Query planner returned invalid JSON: {content}") from error

    if not isinstance(payload, dict):
        raise RuntimeError("Query planner JSON must be an object.")
    return payload


def _clean_semantic_query(value: Any, fallback_query: str) -> str:
    """Ensure semantic query is a non-empty string."""
    if isinstance(value, str) and value.strip():
        return value.strip()
    return fallback_query


def _is_safe_where_filter(value: Any) -> bool:
    """Validate that the LLM output conforms to the allowed filter schema."""
    if value is None:
        return True

    if not isinstance(value, dict) or not value:
        return False

    if len(value) != 1:
        return False

    key, inner_value = next(iter(value.items()))

    if key in ALLOWED_LOGICAL_OPERATORS:
        if not isinstance(inner_value, list) or not inner_value:
            return False
        return all(_is_safe_where_filter(item) for item in inner_value)

    if key not in ALLOWED_FIELDS:
        return False

    if key in {"countries", "genres"}:
        if not isinstance(inner_value, dict):
            return False
        if set(inner_value.keys()) != {"$contains"}:
            return False
        contains_val = inner_value["$contains"]
        return isinstance(contains_val, str) and bool(contains_val.strip())

    if key == "type":
        return inner_value in {"Movie", "TV Show"}

    if key == "rating":
        return isinstance(inner_value, str) and bool(inner_value.strip())

    if key == "release_year":
        if isinstance(inner_value, bool):
            return False
        if isinstance(inner_value, int):
            return True
        if not isinstance(inner_value, dict) or not inner_value:
            return False
        for op, year in inner_value.items():
            if op not in ALLOWED_YEAR_OPERATORS or isinstance(year, bool) or not isinstance(year, int):
                return False
        return True

    return False


def parse_search_plan(content: str, fallback_query: str) -> SearchPlan:
    """Parse LLM output into a validated SearchPlan."""
    try:
        payload = _load_json_object(content)
    except Exception as e:
        logger.warning("Failed to parse search plan JSON: %s", e)
        return _fallback_search_plan(fallback_query)

    semantic_query = _clean_semantic_query(payload.get("semantic_query"), fallback_query)
    where = payload.get("where")
    if not _is_safe_where_filter(where):
        logger.warning("Unsafe or invalid where filter discarded: %s", where)
        where = None

    return SearchPlan(semantic_query=semantic_query, where=where)


def create_search_plan(question: str) -> SearchPlan:
    """Generate a structured search plan using the LLM query intelligence layer."""
    load_dotenv(dotenv_path=ENV_PATH, override=False)

    api_key = os.getenv("GROQ_API_KEY", "").strip()
    if not api_key:
        logger.info("GROQ_API_KEY not configured; using fallback search plan.")
        return _fallback_search_plan(question)

    model = os.getenv("GROQ_MODEL", "qwen/qwen3.8-27b")

    try:
        from groq import Groq

        client = Groq(api_key=api_key)
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": SYSTEM_MESSAGE},
                {"role": "user", "content": question},
            ],
            temperature=0.0,
            max_tokens=500,
        )
        content = response.choices[0].message.content
        if not content:
            return _fallback_search_plan(question)

        plan = parse_search_plan(content.strip(), fallback_query=question)
        logger.info(
            "Query intelligence generated plan: semantic_query='%s', where=%s",
            plan.semantic_query,
            plan.where,
        )
        return plan
    except Exception as e:
        logger.warning("Query intelligence LLM call failed: %s; falling back to direct search", e)
        return _fallback_search_plan(question)
